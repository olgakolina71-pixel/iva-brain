"""IVA Brain Experiment 01: learn a tiny world's dynamics from online experience.

This is deliberately a narrow ML experiment, not a claim of general intelligence.
It uses no dataset: transitions are generated by the agent interacting with the
sandbox and are used for online updates immediately.
"""
from __future__ import annotations
import argparse, random, copy
from collections import deque
from dataclasses import dataclass
import torch
from torch import nn

ACTIONS = ((0, -1), (1, 0), (0, 1), (-1, 0))  # north/east/south/west

@dataclass
class World:
    size: int = 7
    walls: set[tuple[int, int]] | None = None
    position: tuple[int, int] = (0, 0)
    def __post_init__(self):
        if self.walls is None:
            self.walls = {(2, 1), (2, 2), (4, 3), (1, 5), (5, 5)}
        self.position = (0, 0)
    def observe(self):
        x, y = self.position
        blocked=[]
        for dx,dy in ACTIONS:
            nx,ny=x+dx,y+dy
            blocked.append(float(nx<0 or ny<0 or nx>=self.size or ny>=self.size or (nx,ny) in self.walls))
        return torch.tensor([x/(self.size-1), y/(self.size-1), *blocked], dtype=torch.float32)
    def step(self, action:int):
        dx,dy=ACTIONS[action]; x,y=self.position; nx,ny=x+dx,y+dy
        if 0<=nx<self.size and 0<=ny<self.size and (nx,ny) not in self.walls:
            self.position=(nx,ny)
        return self.observe()

class Predictor(nn.Module):
    def __init__(self):
        super().__init__()
        self.net=nn.Sequential(nn.Linear(10,64),nn.ReLU(),nn.Linear(64,64),nn.ReLU(),nn.Linear(64,6),nn.Sigmoid())
    def forward(self, obs, action):
        return self.net(torch.cat([obs, action], dim=-1))

def action_tensor(a):
    t=torch.zeros(4); t[a]=1.; return t

class OnlineAgent:
    def __init__(self, seed=42, ensemble=3):
        torch.manual_seed(seed); random.seed(seed)
        self.models=[Predictor() for _ in range(ensemble)]
        self.opts=[torch.optim.Adam(m.parameters(), lr=0.003) for m in self.models]
        self.buffer=deque(maxlen=256); self.visits={}; self.steps=0
    def choose(self, obs):
        x,y=round(float(obs[0])*6),round(float(obs[1])*6)
        scores=[]
        for a in range(4):
            inp=action_tensor(a)
            preds=torch.stack([m(obs,inp).detach() for m in self.models])
            disagreement=float(preds.var(dim=0, unbiased=False).mean())
            key=(x,y,a); novelty=1.0/(1+self.visits.get(key,0))
            scores.append(0.7*novelty+0.3*disagreement+random.random()*0.05)
        a=max(range(4), key=lambda i:scores[i])
        self.visits[(x,y,a)]=self.visits.get((x,y,a),0)+1
        return a
    def learn(self, obs, action, nxt):
        self.buffer.append((obs.clone(),action_tensor(action),nxt.clone()))
        if len(self.buffer)<8: return None
        batch=random.sample(list(self.buffer), min(32,len(self.buffer)))
        xs=torch.stack([torch.cat([o,a]) for o,a,_ in batch]); ys=torch.stack([n for _,_,n in batch])
        losses=[]
        for model,opt in zip(self.models,self.opts):
            opt.zero_grad(); loss=((model(xs[:,:6],xs[:,6:])-ys)**2).mean(); loss.backward(); opt.step(); losses.append(float(loss.detach()))
        self.steps+=1
        return sum(losses)/len(losses)

def run(episodes=20, steps_per_episode=100, seed=42):
    agent=OnlineAgent(seed); baseline=[copy.deepcopy(m) for m in agent.models]
    world=World(); loss_log=[]; visited=set()
    for ep in range(episodes):
        world.position=(0,0); obs=world.observe()
        for _ in range(steps_per_episode):
            action=agent.choose(obs); nxt=world.step(action)
            visited.add(world.position)
            loss=agent.learn(obs,action,nxt)
            if loss is not None: loss_log.append(loss)
            obs=nxt
    print(f"IVA Brain Experiment 01 | episodes={episodes} | steps={episodes*steps_per_episode}")
    print(f"Unique cells visited: {len(visited)}/{world.size*world.size-len(world.walls)}")
    print(f"Unique state/action choices: {len(agent.visits)}")
    if loss_log:
        n=max(1,len(loss_log)//5)
        chunks=[sum(loss_log[i:i+n])/len(loss_log[i:i+n]) for i in range(0,len(loss_log),n)]
        print("Online loss by chronological chunks:", " -> ".join(f"{v:.4f}" for v in chunks))
        print(f"Final rolling mean loss: {sum(loss_log[-50:])/len(loss_log[-50:]):.4f}")
    # Generated validation transitions are not used for learning.
    test=[]
    for _ in range(200):
        world.position=(random.randrange(world.size),random.randrange(world.size))
        if world.position in world.walls: continue
        o=world.observe(); a=random.randrange(4); target=world.step(a); test.append((o,action_tensor(a),target))
    with torch.no_grad():
        base=sum(((sum(m(o,a) for m in baseline)/len(baseline)-t)**2).mean().item() for o,a,t in test)/len(test)
        trained=sum(((sum(m(o,a) for m in agent.models)/len(agent.models)-t)**2).mean().item() for o,a,t in test)/len(test)
    print(f"Generated validation MSE: untrained={base:.4f} | learned={trained:.4f}")
    torch.save({"models":[m.state_dict() for m in agent.models],"steps":agent.steps,"visits":agent.visits},"iva_exp01_checkpoint.pt")
    print("Checkpoint saved: iva_exp01_checkpoint.pt")

if __name__=="__main__":
    p=argparse.ArgumentParser(); p.add_argument("--episodes",type=int,default=20); p.add_argument("--steps",type=int,default=100); p.add_argument("--seed",type=int,default=42); args=p.parse_args()
    run(args.episodes,args.steps,args.seed)
